CREATE TABLE IF NOT EXISTS terms (
    code varchar(6) PRIMARY KEY CHECK (code ~ '^[0-9]{4}(15|25|35|45)$'),
    label text NOT NULL,
    source_url text NOT NULL,
    available boolean NOT NULL DEFAULT true,
    last_scraped_at timestamptz
);
ALTER TABLE terms ADD COLUMN IF NOT EXISTS is_default boolean NOT NULL DEFAULT false;
CREATE UNIQUE INDEX IF NOT EXISTS terms_one_default_idx ON terms(is_default) WHERE is_default;
CREATE TABLE IF NOT EXISTS instructors (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    rmp_id integer,
    avg_rating numeric(3,2) CHECK (avg_rating BETWEEN 0 AND 5),
    avg_difficulty numeric(3,2) CHECK (avg_difficulty BETWEEN 0 AND 5),
    num_ratings integer CHECK (num_ratings >= 0),
    ratings_updated_at timestamptz
);
CREATE TABLE IF NOT EXISTS courses (
    term_code varchar(6) NOT NULL REFERENCES terms(code),
    crn integer NOT NULL,
    college_code text,
    subject_code text NOT NULL,
    course_number text NOT NULL,
    course_title text NOT NULL,
    section text NOT NULL,
    instruction_type text NOT NULL,
    instruction_method text NOT NULL,
    enrolled integer CHECK (enrolled >= 0),
    capacity integer CHECK (capacity >= 0),
    is_full boolean,
    credits text,
    prerequisites text,
    start_time time,
    end_time time,
    days text[],
    PRIMARY KEY (term_code, crn)
);
CREATE TABLE IF NOT EXISTS course_instructors (
    term_code varchar(6) NOT NULL,
    crn integer NOT NULL,
    instructor_id bigint NOT NULL REFERENCES instructors(id),
    PRIMARY KEY (term_code, crn, instructor_id),
    FOREIGN KEY (term_code, crn) REFERENCES courses(term_code, crn) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS courses_term_subject_number_idx ON courses(term_code, subject_code, course_number);
CREATE INDEX IF NOT EXISTS course_instructors_instructor_term_idx ON course_instructors(instructor_id, term_code);
CREATE INDEX IF NOT EXISTS instructors_name_idx ON instructors(name);
CREATE INDEX IF NOT EXISTS instructors_rmp_id_idx ON instructors(rmp_id);

-- Compatibility names keep existing table formatting and filters working.
CREATE OR REPLACE VIEW all_course_instructor_data AS
SELECT c.term_code, i.id AS instructor_id, i.name AS instructor_name,
    i.rmp_id AS instructor_rmp_id, i.avg_difficulty, i.avg_rating, i.num_ratings,
    c.crn AS course_id, c.subject_code, c.course_number, c.instruction_type,
    c.instruction_method, c.section,
    CASE WHEN c.is_full THEN 'FULL' ELSE c.enrolled::text END AS enroll,
    c.capacity::text AS max_enroll, c.course_title, c.credits,
    c.prerequisites AS prereqs, c.start_time, c.end_time, c.days
FROM courses c
LEFT JOIN course_instructors ci ON (c.term_code,c.crn)=(ci.term_code,ci.crn)
LEFT JOIN instructors i ON i.id=ci.instructor_id;
